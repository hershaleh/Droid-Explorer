package com.droidexplorer.ui.design

import androidx.compose.runtime.Immutable
import androidx.compose.ui.graphics.Color

/**
 * Colour tokens modelled on the public WinUI 3 / Windows 11 theme resources
 * (names follow the WinUI resource names, e.g. ControlFillColorDefault).
 * Values are approximations written from memory of the public design tokens and
 * must be verified against a real Windows 11 device (see docs/design-fidelity.md).
 */
@Immutable
class FluentColors(
    val isDark: Boolean,
    // Window and layers (Mica is emulated by a solid base colour).
    val windowBackground: Color,
    val windowBackgroundSecondary: Color,
    val windowBackgroundTertiary: Color,
    val windowBackgroundQuarternary: Color,
    val layer: Color,
    // Cards
    val cardFill: Color,
    val cardFillSecondary: Color,
    val cardStroke: Color,
    // Controls
    val controlFill: Color,
    val controlFillSecondary: Color,
    val controlFillTertiary: Color,
    val controlFillDisabled: Color,
    val controlFillInput: Color,
    val controlFillInputActive: Color,
    val controlStroke: Color,
    val controlStrokeSecondary: Color,
    val controlStrongStroke: Color,
    val controlStrongStrokeDisabled: Color,
    val controlStrokeOnAccent: Color,
    val controlStrokeOnAccentSecondary: Color,
    val subtleFillSecondary: Color,
    val subtleFillTertiary: Color,
    // Text
    val textPrimary: Color,
    val textSecondary: Color,
    val textTertiary: Color,
    val textDisabled: Color,
    val textOnAccent: Color,
    val textOnAccentDisabled: Color,
    // Accent
    val accent: Color,
    val accentSecondary: Color,
    val accentTertiary: Color,
    val accentDisabled: Color,
    val accentText: Color,
    // Misc
    val divider: Color,
    val flyoutFill: Color,
    val surfaceStroke: Color,
    val smoke: Color,
    val focusOuter: Color,
    val focusInner: Color,
    // System status
    val critical: Color,
    val success: Color,
    val caution: Color,
    val attention: Color,
    val criticalBackground: Color,
    val successBackground: Color,
    val cautionBackground: Color,
    val attentionBackground: Color,
)

