package com.droidexplorer.feature.files

/** Everything the Explorer screen can ask its host to do. Defaults make the screen usable as a static preview. */
data class ExplorerActions(
    val canBack: Boolean = false,
    val canForward: Boolean = false,
    val canUp: Boolean = false,
    val onBack: () -> Unit = {},
    val onForward: () -> Unit = {},
    val onUp: () -> Unit = {},
    val onRefresh: () -> Unit = {},
    val onOpen: (ExplorerItem) -> Unit = {},
    val onToggleSelect: (ExplorerItem) -> Unit = {},
    val onCrumb: (Int) -> Unit = {},
    val editablePath: String? = null,
    val onPathSubmit: (String) -> Unit = {},
    val onMenu: (() -> Unit)? = null,
    val canPaste: Boolean = false,
    val sortKey: com.droidexplorer.storage.api.SortKey = com.droidexplorer.storage.api.SortKey.NAME,
    val sortAscending: Boolean = true,
    val onNewFolder: () -> Unit = {},
    val onCut: () -> Unit = {},
    val onCopy: () -> Unit = {},
    val onPaste: () -> Unit = {},
    val onRename: () -> Unit = {},
    val onShare: () -> Unit = {},
    val onDelete: () -> Unit = {},
    val onSort: (com.droidexplorer.storage.api.SortKey, Boolean) -> Unit = { _, _ -> },
    val viewMode: ViewMode = ViewMode.Details,
    val onViewMode: (ViewMode) -> Unit = {},
    val groupBy: GroupBy = GroupBy.Date,
    val onGroupBy: (GroupBy) -> Unit = {},
    val showHidden: Boolean = false,
    val onShowHidden: (Boolean) -> Unit = {},
    val onSelectAll: () -> Unit = {},
    val onSelectNone: () -> Unit = {},
    val onInvertSelection: () -> Unit = {},
    val query: String = "",
    val onQuery: (String) -> Unit = {},
    val searchHint: String? = null,
    val renamingPath: String? = null,
    val onRenameCommit: (String, String) -> Unit = { _, _ -> },
    val onRenameCancel: () -> Unit = {},
    /** Filled in by the screen from the item list. */
    val selectedCount: Int = 0,
    val singleIsFolder: Boolean = false,
    val onOpenWith: () -> Unit = {},
    val onCopyPath: () -> Unit = {},
    val onProperties: () -> Unit = {},
    val onOpenSelected: () -> Unit = {},
    /** Null when no terminal app (Termux) is installed. */
    val onOpenTerminal: (() -> Unit)? = null,
)
